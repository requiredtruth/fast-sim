# packs assets/sfx/*.ogg into build/sfx.c. every clip is decoded and joined into one vorbis stream,
# because a vorbis header costs ~3 KB per file and there are ~30 clips.
# name.ogg, name_2.ogg ... are variants of the sound whose name matches the S_* enum in game.h.
import glob, os, re, subprocess, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SR = 32000
GAP = 256
Q = "0.5"
VSR = 16000
VQ = "0"

names = re.search(r"enum \{\s*(S_PISTOL.*?)S_COUNT", open(f"{ROOT}/src/game.h").read(), re.S).group(1)
names = [n.strip()[2:].lower() for n in names.replace("\n", " ").split(",") if n.strip()]

def stream(group, sr, q, cut=()):
    pcm, starts, offsets = b"", [], []
    for name in group:
        files = [f"{ROOT}/assets/sfx/{name}.ogg"] + sorted(glob.glob(f"{ROOT}/assets/sfx/{name}_[0-9].ogg"))
        offsets.append(len(starts))
        for f in files:
            if not os.path.exists(f): sys.exit("missing " + f)
            raw = subprocess.run(["ffmpeg", "-v", "error", "-i", f, "-ac", "1", "-ar", str(sr), "-f", "s16le", "-"],
                                 capture_output=True, check=True).stdout
            starts.append(len(pcm) // 2)
            pcm += raw + bytes(GAP * 2)
    starts.append(len(pcm) // 2)
    ogg = subprocess.run(["ffmpeg", "-v", "error", "-f", "s16le", "-ar", str(sr), "-ac", "1", "-i", "-",
                          "-c:a", "libvorbis", "-q:a", q, *cut, "-f", "ogg", "-"],
                         input=pcm, capture_output=True, check=True).stdout
    return ogg, offsets, starts, len(pcm) // 2

# the voice lines (v_*) are a second stream: speech at 16 kHz and a very low quality is a third of the size
sfx_names = [n for n in names if not n.startswith("v_")]
ogg, offsets, starts, _ = stream(sfx_names, SR, Q)
vogg, voffsets, vstarts, vlen = stream([n for n in names if n.startswith("v_")], VSR, VQ, ["-cutoff", "3700"])
nplain = len(starts) - 1
offsets += [nplain + o for o in voffsets] + [nplain + len(vstarts) - 1]

def arr(ctype, name, vals):
    return f"const {ctype} {name}[] = {{\n" + "".join(
        "    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",\n" for i in range(0, len(vals), 16)) + "};\n"

os.makedirs(f"{ROOT}/build", exist_ok=True)
with open(f"{ROOT}/build/sfx.c", "w") as o:
    o.write("// generated by tools/pack_sfx.py\n")
    o.write(arr("unsigned char", "sfx_blob", list(ogg)))
    o.write(f"const int sfx_blob_len = {len(ogg)};\n")
    o.write(f"const int sfx_rate = {SR};\n")
    o.write(arr("int", "sfx_offsets", offsets))     # clips of sound i are sfx_offsets[i] .. sfx_offsets[i + 1]
    o.write(arr("int", "sfx_clip_start", starts))   # sample index of each clip in the decoded stream
    o.write(arr("unsigned char", "voice_blob", list(vogg)))
    o.write(f"const int voice_blob_len = {len(vogg)};\nconst int voice_rate = {VSR};\nconst int sfx_plain = {nplain};\n")
    o.write(arr("int", "voice_clip_start", vstarts))   # same, for the voice stream; clips follow the plain ones
for i, n in enumerate(names):
    print(f"{n:12s} {offsets[i + 1] - offsets[i]} clip(s)")
print(f"sfx: {nplain} clips, {starts[-1] / SR:.1f} s, {len(ogg)} bytes")
print(f"voice: {len(vstarts) - 1} clips, {vlen / VSR:.1f} s, {len(vogg)} bytes")
